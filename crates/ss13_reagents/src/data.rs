//! Reagent and reaction definitions as `ss13-mapload convert` writes them ([`CHEM_FILE`]) from
//! the static vars of tg `/datum/reagent` and `/datum/chemical_reaction` subtypes.

use std::path::Path;

use anyhow::Context as _;
use serde::{Deserialize, Serialize};

/// `<assets>/reagents.ron`.
pub const CHEM_FILE: &str = "reagents.ron";

/// One tg `/datum/reagent` type, every var resolved through inheritance.
#[derive(Serialize, Deserialize, Clone, Debug, PartialEq)]
pub struct ReagentDef {
    pub path: String,
    pub name: String,
    pub description: String,
    /// DM color string: `#RRGGBB` or `#RRGGBBAA`.
    pub color: String,
    pub taste_description: String,
    pub taste_mult: f32,
    /// Units per second (`REAGENTS_METABOLISM` = 0.2).
    pub metabolization_rate: f32,
    /// 0: none.
    pub overdose_threshold: f32,
    pub ph: f32,
    pub specific_heat: f32,
    /// `REAGENT_*` bits (`chemical_flags`), with what `New()` adds (`/datum/reagent/consumable`:
    /// `REAGENT_UNAFFECTED_BY_METABOLISM`).
    pub chemical_flags: u32,
    /// `initial(purity)` and the purity a fresh reagent gets (`creation_purity`).
    pub purity: f32,
    pub creation_purity: f32,
    pub inverse_chem: Option<String>,
    pub inverse_chem_val: f32,
    pub purge_multiplier: f32,
    /// `/datum/reagent/toxin`: `toxpwr`, `health_required`, `liver_tolerance_multiplier`.
    #[serde(default)]
    pub toxpwr: f32,
    #[serde(default)]
    pub health_required: f32,
    #[serde(default)]
    pub liver_tolerance_multiplier: f32,
    /// `/datum/reagent/consumable/ethanol`: `boozepwr`.
    #[serde(default)]
    pub boozepwr: f32,
    /// `/datum/reagent/consumable/nutriment`: `brute_heal`.
    #[serde(default)]
    pub brute_heal: f32,
    /// `/datum/reagent/consumable`: `nutriment_factor`.
    #[serde(default)]
    pub nutriment_factor: f32,
    /// `default_container`: what the ChemMaster suggests for it (a type path).
    #[serde(default)]
    pub default_container: String,
}

/// One tg `/datum/chemical_reaction` type. Reagent lists keep their DM order (it decides what is
/// removed and added first).
#[derive(Serialize, Deserialize, Clone, Debug, PartialEq)]
pub struct ReactionDef {
    pub path: String,
    pub required_reagents: Vec<(String, f32)>,
    pub results: Vec<(String, f32)>,
    pub required_catalysts: Vec<(String, f32)>,
    pub required_container: Option<String>,
    pub required_container_accepts_subtypes: bool,
    pub mob_react: bool,
    pub mix_message: String,
    pub is_cold_recipe: bool,
    pub required_temp: f32,
    pub optimal_temp: f32,
    pub overheat_temp: f32,
    pub optimal_ph_min: f32,
    pub optimal_ph_max: f32,
    pub determin_ph_range: f32,
    pub temp_exponent_factor: f32,
    pub ph_exponent_factor: f32,
    pub thermic_constant: f32,
    #[serde(rename = "H_ion_release")]
    pub h_ion_release: f32,
    pub rate_up_lim: f32,
    pub purity_min: f32,
    /// `REACTION_*` bits.
    pub reaction_flags: u32,
    /// The type overrides `on_reaction`, `reaction_step`, `reaction_finish`, `overheated` or
    /// `overly_impure`: what those procs do beyond moving reagents is not modelled.
    pub special: bool,
    /// A `/datum/chemical_reaction/reagent_explosion` that only has its base `on_reaction`.
    #[serde(default)]
    pub explosion: Option<ExplosionDef>,
}

/// `reagent_explosion`'s `strengthdiv` and `modifier`: power `modifier + round(volume /
/// strengthdiv)`.
#[derive(Serialize, Deserialize, Clone, Copy, Debug, PartialEq)]
pub struct ExplosionDef {
    pub strengthdiv: f32,
    pub modifier: f32,
}

/// One tg `/datum/glass_style` (`reagent_containers/cups/_glass_datum.dm`): a container of
/// exactly `container`'s type whose main reagent is exactly `drink` looks like this.
#[derive(Serialize, Deserialize, Clone, Debug, Default, PartialEq)]
pub struct GlassStyleDef {
    pub container: String,
    pub drink: String,
    /// Empty: the container keeps its name (or description).
    pub name: String,
    pub desc: String,
    /// Empty: the container keeps its sprite.
    pub icon: String,
    pub icon_state: String,
}

#[derive(Serialize, Deserialize, Clone, Debug, Default, PartialEq)]
pub struct ChemData {
    pub reagents: Vec<ReagentDef>,
    pub reactions: Vec<ReactionDef>,
    #[serde(default)]
    pub glass_styles: Vec<GlassStyleDef>,
}

impl ChemData {
    pub fn read(path: &Path) -> anyhow::Result<Self> {
        let text = ss13_data::read_to_string(path)
            .with_context(|| format!("reading {}", path.display()))?;
        ron::from_str(&text).with_context(|| format!("parsing {}", path.display()))
    }

    pub fn to_ron(&self) -> String {
        let mut out = String::from(
            "// Generated by `ss13-mapload convert` from dm_types.json. Do not edit.\n",
        );
        out.push_str(
            &ron::ser::to_string_pretty(self, ron::ser::PrettyConfig::default())
                .expect("plain data always serializes"),
        );
        out.push('\n');
        out
    }
}
