//! Crafting menu recipes from the DM dump, written by `ss13-mapload convert` to [`CRAFTING_FILE`]:
//! every `/datum/crafting_recipe` subtype as tg's `init_crafting_recipes` builds it
//! (`code/__HELPERS/global_lists.dm`, `code/datums/components/crafting/_recipes.dm`), with the
//! food recipe fields (`code/modules/food_and_drinks/recipes/food_mixtures.dm`) and the guide
//! recipes that read their requirements from a chemical reaction
//! (`recipes_guide.dm` `setup_chemical_reaction_details`, `soup_guide.dm`). The game
//! (`ss13_game::crafting`) reads it at startup.
// shortcut: the stack recipes tg also lists in the crafting menu (`/datum/crafting_recipe/stack`,
// built from the sheets' recipe lists at runtime) are not converted: stacks have their own menu
// (`ss13_game::stack_recipes`).

