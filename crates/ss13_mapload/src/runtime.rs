pub fn runtime_types() -> BTreeSet<&'static str> {
    use crate::{antag, atmos_machine, cargo, mobs, service, silicon};
    let mut out = BTreeSet::new();
    let tables: [&[&'static str]; 35] = [
        &crate::RUNTIME_TYPES,
        &crate::RUNTIME_CONTAINER_TYPES,
        &crate::CONSTRUCTION_TYPES,
        &crate::MEDICAL_RUNTIME_TYPES,
        &crate::DISPOSAL_RUNTIME_TYPES,
        crate::ENGMISC_RUNTIME_TYPES,
        &crate::BOT_RUNTIME_TYPES,
        &crate::WALLMOUNT_RUNTIME_TYPES,
        &crate::FRAME_RUNTIME_TYPES,
        &antag::CHANGELING_RUNTIME_TYPES,
        &antag::CULT_RUNTIME_TYPES,
        &antag::HERETIC_RUNTIME_TYPES,
        &antag::WIZARD_RUNTIME_TYPES,
        &antag::ABDUCTOR_RUNTIME_TYPES,
        &antag::ZOMBIE_RUNTIME_TYPES,
        &antag::RAIDER_RUNTIME_TYPES,
        &mobs::MOB_RUNTIME_TYPES,
        &crate::restaurant::RESTAURANT_RUNTIME_TYPES,
        &silicon::CAMERA_RUNTIME_TYPES,
        &silicon::SILICON_TYPES,
        // The chaplain's gear, the null rod's forms and what rites make (`ss13_game::service`).
        &service::RELIGION_RUNTIME_TYPES,
        &service::NULLROD_VARIANTS,
        &service::HOLY_ARMOR_KITS,
        &service::MACHINE_BLESSINGS,
        // Supply crates' bounty cubes, mail and manifests.
        &cargo::RUNTIME_TYPES,
        GAME_RUNTIME_TYPES,
        SPECIES_RUNTIME_TYPES,
        CYBERIMP_RUNTIME_TYPES,
        EVENT_RUNTIME_TYPES,
        EXPLORATION_RUNTIME_TYPES,
        BITRUNNING_RUNTIME_TYPES,
        BITRUNNING_DISK_TYPES,
        GIFT_TYPES,
        SECDEF_RUNTIME_TYPES,
        SKILLCHIP_RUNTIME_TYPES,
    ];
    out.extend(tables.into_iter().flatten().copied());
    // What a bullet or a fragment leaves in a body (`ss13_game::embedding`).
    out.extend(crate::embed::SHRAPNEL_RUNTIME_TYPES);
    // What the food reactions make (`ss13_game::chem`).
    out.extend(crate::food::FOOD_REACTION_RESULTS);
    out.extend(crate::food::FOOD_MESS_TYPES);
    // Conjured things, the Grand Ritual, the runic scepter, the demon bottles (`ss13_game`).
    out.extend(antag::SPELL_RUNTIME_TYPES);
    // Spider eggs, cocoons, webs and the spiders' life stages (`ss13_game::antag::spiders`).
    out.extend(antag::SPIDER_RUNTIME_TYPES);
    // Ash walker eggs and the nest's anomaly core (`ss13_game::antag::ashwalker`).
    out.extend(antag::ASHWALKER_RUNTIME_TYPES);
    // The voidwalker, its windows and drops (`ss13_game::antag::voidwalker`).
    out.extend(antag::VOIDWALKER_RUNTIME_TYPES);
    // Completed golem shells and what they fall apart into (`ss13_game::golems`).
    out.extend(crate::mob_spawn::GOLEM_RUNTIME_TYPES);
    out.extend(crate::mob_spawn::GOLEM_STACK_FOOD);
    // Lavaland fauna, their spawns and drops (`ss13_game::mobs::lavaland`).
    out.extend(mobs::LAVALAND_RUNTIME_TYPES);
    // The lavaland bosses, their bolts and chests (`ss13_game::mobs::megafauna`).
    out.extend(mobs::MEGAFAUNA_RUNTIME_TYPES);
    // Catches and the prefilled aquarium's fish (`ss13_game::fishing`).
    out.extend(crate::fishing::runtime_types());
    // What the stack crafting menus make (`ss13_game::stack_recipes`).
    out.extend(crate::stack_recipe_types::STACK_RECIPE_RESULTS);
    out.extend(CARGO_FLORA_RUNTIME_TYPES);
    // What growing vats grow and the dish the microscope hands back (`ss13_game::science`).
    out.extend(crate::cell_line_types::CELL_LINE_RESULTS);
    out.insert("/obj/item/petri_dish");
    // What the disposal pipe dispenser makes (`ss13_game::recycling`).
    out.extend(crate::engmisc::disposal_recipe_paths());
    // Log planks and plant mobs (`ss13_game::botany`).
    out.extend(crate::plants::BOTANY_RUNTIME_TYPES);
    // A canister's `relabel` copies another canister type's name and look.
    out.extend(atmos_machine::CANISTER_LABELS.iter().map(|&(_, path)| path));
    // Cutting a stationary tank open leaves its frame; wrenching pipes, devices and meters off
    // leaves fittings; the pipe dispenser and RPD make every recipe's machine.
    out.extend([
        atmos_machine::TANK_FRAME,
        atmos_machine::PIPE_FITTING,
        atmos_machine::PIPE_METER_ITEM,
        atmos_machine::PIPE_DISPENSER,
        "/obj/item/pipe_dispenser",
    ]);
    for (_, recipes) in atmos_machine::ATMOS_PIPE_RECIPES {
        out.extend(recipes.iter().filter_map(|r| r.path));
    }
    // The crystallizer makes its recipes' products.
    for recipe in atmos_machine::CRYSTALLIZER_RECIPES {
        out.extend(recipe.products.iter().map(|&(path, _)| path));
    }
    out
}
