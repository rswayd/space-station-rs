/// On a placed human mob spawner: its type, the key into [`MobSpawnData`].
#[derive(Component, Reflect, Default, Clone, Debug, PartialEq)]
pub struct DmMobSpawn {
    pub path: String,
}

/// The vars of one spawner type.
#[derive(Clone, Debug, Default, PartialEq, Serialize, Deserialize)]
pub struct MobSpawnDef {
    pub path: String,
    /// `/obj/effect/mob_spawn/corpse`: a dead body at map load, no ghost role.
    pub corpse: bool,
    /// `name`: the role in the spawners menu.
    pub name: String,
    pub prompt_name: String,
    pub you_are_text: String,
    pub flavour_text: String,
    pub important_text: String,
    pub uses: u32,
    pub infinite_use: bool,
    pub deletes_on_zero_uses_left: bool,
    /// `temp_body`: the ghost may still re-enter its old body.
    pub temp_body: bool,
    pub mob_name: Option<String>,
    /// `mob_species` type path.
    pub mob_species: Option<String>,
    pub outfit: Option<Outfit>,
    pub faction: Vec<String>,
    pub brute_damage: f32,
    pub burn_damage: f32,
    pub oxy_damage: f32,
    pub husk: bool,
    /// `mob_type`, read for the drone shells (the humans' is always a human).
    #[serde(default)]
    pub mob_type: Option<String>,
}

#[derive(Clone, Debug, Default, PartialEq, Serialize, Deserialize)]
pub struct MobSpawnData {
    pub spawns: Vec<MobSpawnDef>,
}

impl MobSpawnData {
    pub fn read(path: &Path) -> anyhow::Result<Self> {
        crate::read_ron(path)
    }

    pub fn to_ron(&self) -> String {
        let mut out = String::from("// Generated by `ss13-mapload convert`. Do not edit.\n");
        out.push_str(
            &ron::ser::to_string_pretty(self, ron::ser::PrettyConfig::default())
                .expect("mob spawn data serializes"),
        );
        out.push('\n');
        out
    }

    pub fn get(&self, path: &str) -> Option<&MobSpawnDef> {
        self.spawns.iter().find(|s| s.path == path)
    }

    /// Every item the outfits spawn: the converter emits prototypes for them.
    pub fn item_types(&self) -> BTreeSet<&str> {
        self.spawns
            .iter()
            .filter_map(|s| s.outfit.as_ref())
            .flat_map(|o| {
                o.items
                    .iter()
                    .map(|(_, p)| p.as_str())
                    .chain(o.backpack_contents.iter().map(|(p, _)| p.as_str()))
                    .chain(o.belt_contents.iter().map(|(p, _)| p.as_str()))
                    .chain(o.accessory.as_deref())
            })
            .collect()
    }
}

fn is_spawn(path: &str) -> bool {
    is_under(path, GHOST_ROLE_ROOT)
        || is_under(path, CORPSE_ROOT)
        || is_under(path, DRONE_SHELL_ROOT)
}

fn text(v: Option<&Value>) -> String {
    v.and_then(Value::as_str).unwrap_or_default().to_owned()
}

fn path_of(v: Option<&Value>) -> Option<String> {
    v?.get("path")?.as_str().map(str::to_owned)
}

fn strings(v: Option<&Value>) -> Vec<String> {
    match v {
        Some(Value::String(s)) => vec![s.clone()],
        _ => v
            .and_then(|v| v.get("list"))
            .and_then(Value::as_array)
            .map(|l| {
                l.iter()
                    .filter_map(|i| i.as_str().map(str::to_owned))
                    .collect()
            })
            .unwrap_or_default(),
    }
}

/// [`MobSpawnDef`] of every human ghost role and corpse type.
pub fn resolve(types: &DmTypes) -> MobSpawnData {
    let mut spawns: Vec<MobSpawnDef> = types
        .types
        .keys()
        .filter(|p| is_spawn(p))
        .map(|p| {
            let r = |var: &str| types.resolved(p, var);
            let damage = |var: &str| num(r(var)).unwrap_or(0.0) as f32;
            MobSpawnDef {
                path: p.clone(),
                corpse: is_under(p, CORPSE_ROOT),
                name: text(r("name")),
                prompt_name: text(r("prompt_name")),
                you_are_text: text(r("you_are_text")),
                flavour_text: text(r("flavour_text")),
                important_text: text(r("important_text")),
                uses: num(r("uses")).unwrap_or(1.0).max(0.0) as u32,
                infinite_use: truthy(r("infinite_use")),
                // `deletes_on_zero_uses_left = TRUE` unless a type says otherwise.
                deletes_on_zero_uses_left: r("deletes_on_zero_uses_left").is_none()
                    || truthy(r("deletes_on_zero_uses_left")),
                temp_body: truthy(r("temp_body")),
                mob_name: Some(text(r("mob_name"))).filter(|n| !n.is_empty()),
                mob_species: path_of(r("mob_species")),
                outfit: path_of(r("outfit"))
                    .filter(|o| types.types.contains_key(o))
                    .map(|o| crate::jobs::outfit(types, &o)),
                faction: strings(r("faction")),
                brute_damage: damage("brute_damage"),
                burn_damage: damage("burn_damage"),
                oxy_damage: damage("oxy_damage"),
                husk: truthy(r("husk")),
                mob_type: is_under(p, DRONE_SHELL_ROOT)
                    .then(|| path_of(r("mob_type")))
                    .flatten(),
            }
        })
        .collect();
    spawns.sort_by(|a, b| a.path.cmp(&b.path));
    MobSpawnData { spawns }
}

/// Converter fields: every human ghost role and corpse type carries its path.
pub fn type_fields(types: &DmTypes, path: &str) -> Vec<Field> {
    if !types.types.contains_key(path) || !is_spawn(path) {
        return Vec::new();
    }
    vec![ext(COMPONENT, "path", format!("{path:?}"))]
}

#[cfg(test)]
mod tests {
    use super::*;

    const TYPES: &str = r##"{
      "schema": 3,
      "types": {
        "/datum": { "parent": null },
        "/datum/outfit": { "parent": "/datum", "declared_vars": { "uniform": null, "shoes": null } },
        "/datum/outfit/beachbum": { "parent": "/datum/outfit", "declared_vars": {
            "uniform": { "path": "/obj/item/clothing/under/pants/jeans" },
            "shoes": { "path": "/obj/item/clothing/shoes/sandal" } } },
        "/atom": { "parent": "/datum" },
        "/obj": { "parent": "/atom" },
        "/obj/effect": { "parent": "/obj" },
        "/obj/effect/mob_spawn": { "parent": "/obj/effect", "declared_vars": {
            "name": "Mob Spawner", "mob_name": null, "outfit": null, "mob_species": null,
            "faction": null } },
        "/obj/effect/mob_spawn/ghost_role": { "parent": "/obj/effect/mob_spawn", "declared_vars": {
            "uses": 1, "you_are_text": "", "flavour_text": "", "important_text": "",
            "prompt_name": "", "temp_body": 0, "infinite_use": 0, "deletes_on_zero_uses_left": 1 } },
        "/obj/effect/mob_spawn/ghost_role/human": { "parent": "/obj/effect/mob_spawn/ghost_role" },
        "/obj/effect/mob_spawn/ghost_role/human/beach": { "parent": "/obj/effect/mob_spawn/ghost_role/human",
            "declared_vars": { "name": "beach bum sleeper", "prompt_name": "a beach bum",
            "you_are_text": "You're, like, totally a dudebro, bruh.", "uses": 2,
            "outfit": { "path": "/datum/outfit/beachbum" } } },
        "/obj/effect/mob_spawn/corpse": { "parent": "/obj/effect/mob_spawn", "declared_vars": {
            "brute_damage": 0, "oxy_damage": 0, "burn_damage": 0 } },
        "/obj/effect/mob_spawn/corpse/human": { "parent": "/obj/effect/mob_spawn/corpse",
            "declared_vars": { "husk": 0 } },
        "/obj/effect/mob_spawn/corpse/human/damaged": { "parent": "/obj/effect/mob_spawn/corpse/human",
            "declared_vars": { "brute_damage": 1000 } },
        "/obj/effect/mob_spawn/cockroach": { "parent": "/obj/effect/mob_spawn" },
        "/obj/effect/mob_spawn/ghost_role/drone": { "parent": "/obj/effect/mob_spawn/ghost_role",
            "declared_vars": { "name": "drone shell", "mob_name": "drone",
            "mob_type": { "path": "/mob/living/basic/drone" } } },
        "/obj/effect/mob_spawn/ghost_role/drone/classic": {
            "parent": "/obj/effect/mob_spawn/ghost_role/drone",
            "declared_vars": { "mob_type": { "path": "/mob/living/basic/drone/classic" } } }
      }
    }"##;

    #[test]
    fn human_roles_and_corpses_resolve_with_their_outfits() {
        let types = DmTypes::parse(TYPES.as_bytes()).unwrap();
        let data = resolve(&types);
        assert!(data.get("/obj/effect/mob_spawn/cockroach").is_none());
        let beach = data
            .get("/obj/effect/mob_spawn/ghost_role/human/beach")
            .unwrap();
        assert!(!beach.corpse);
        assert_eq!(beach.uses, 2);
        assert_eq!(beach.prompt_name, "a beach bum");
        assert!(beach.deletes_on_zero_uses_left);
        let outfit = beach.outfit.as_ref().unwrap();
        assert_eq!(outfit.path, "/datum/outfit/beachbum");
        assert!(
            data.item_types()
                .contains("/obj/item/clothing/shoes/sandal")
        );
        let corpse = data
            .get("/obj/effect/mob_spawn/corpse/human/damaged")
            .unwrap();
        assert!(corpse.corpse);
        assert_eq!(corpse.brute_damage, 1000.0);
        assert_eq!(
            type_fields(&types, "/obj/effect/mob_spawn/corpse/human/damaged").len(),
            1
        );
        assert!(type_fields(&types, "/obj/effect/mob_spawn/cockroach").is_empty());
    }

    #[test]
    fn drone_shells_resolve_with_their_mob_type() {
        let types = DmTypes::parse(TYPES.as_bytes()).unwrap();
        let data = resolve(&types);
        let classic = data
            .get("/obj/effect/mob_spawn/ghost_role/drone/classic")
            .unwrap();
        assert!(!classic.corpse);
        assert_eq!(classic.name, "drone shell");
        assert_eq!(classic.mob_name.as_deref(), Some("drone"));
        assert_eq!(
            classic.mob_type.as_deref(),
            Some("/mob/living/basic/drone/classic")
        );
        // A human role has none: the game makes a human.
        let beach = data
            .get("/obj/effect/mob_spawn/ghost_role/human/beach")
            .unwrap();
        assert_eq!(beach.mob_type, None);
    }
}
