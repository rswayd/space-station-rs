#!/usr/bin/env python3
"""Writes crates/ss13_game/src/antag/heretic/data.rs: the heretic knowledge, the paths and the
influence strings, from the DM dump (`ss13_dm_extract` -> dm_types.json) and the BYOND checkout's
`strings/antagonist_flavor/heretic_influences.json`.

    python3 -I scripts/gen-heretic-data.py <dm_types.json> [<BandaStation checkout>]

Rerun after BandaStation changes the heretic knowledge (`code/modules/antagonists/heretic/`).
"""

import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "crates/ss13_game/src/antag/heretic/data.rs")

types = json.load(open(sys.argv[1]))["types"]
source = sys.argv[2] if len(sys.argv) > 2 else "../BandaStation"
strings = json.load(open(os.path.join(source, "strings/antagonist_flavor/heretic_influences.json")))


def var(path, name, default=None):
    """A var as the type sees it: declared here or inherited."""
    while path:
        t = types.get(path)
        if t is None:
            return default
        if name in t.get("declared_vars", {}):
            return t["declared_vars"][name]
        path = t.get("parent")
    return default


def is_under(path, root):
    return path == root or path.startswith(root + "/")


def plain(v):
    if isinstance(v, dict):
        if "path" in v:
            return v["path"]
        if "resource" in v:
            return v["resource"]
    return v


def lst(v):
    if not isinstance(v, dict) or "list" not in v:
        return []
    return v["list"]


def assoc(v):
    out = []
    for e in lst(v):
        if isinstance(e, dict) and "assoc" in e:
            out.append((e["assoc"][0], e["assoc"][1]))
        else:
            out.append((e, 1))
    return out


def rs(s):
    if s is None:
        s = ""
    return json.dumps(str(s), ensure_ascii=False)


def num(v, default=0):
    return default if v is None else v


def abstract(path):
    return plain(var(path, "abstract_type")) == path


def kind(path):
    for root, k in [
        ("/datum/heretic_knowledge/spell", "Spell"),
        ("/datum/heretic_knowledge/limited_amount/starting", "Starting"),
        ("/datum/heretic_knowledge/limited_amount", "Limited"),
        ("/datum/heretic_knowledge/blade_upgrade", "BladeUpgrade"),
        ("/datum/heretic_knowledge/summon", "Summon"),
        ("/datum/heretic_knowledge/ultimate", "Ultimate"),
        ("/datum/heretic_knowledge/knowledge_ritual", "KnowledgeRitual"),
        ("/datum/heretic_knowledge/curse", "Curse"),
        ("/datum/heretic_knowledge/armor", "Armor"),
    ]:
        if is_under(path, root):
            return k
    return "Other"


def icon_of(path):
    """`get_icon_of_knowledge`: (dmi, state)."""
    icon_path = plain(var(path, "research_tree_icon_path"))
    if icon_path:
        return icon_path, var(path, "research_tree_icon_state") or ""
    k = kind(path)
    if k == "Spell":
        action = plain(var(path, "action_to_add"))
        if action:
            return plain(var(action, "button_icon")) or "", var(action, "button_icon_state") or ""
    if k == "Summon":
        mob = plain(var(path, "mob_to_summon"))
        if mob:
            return plain(var(mob, "icon")) or "", var(mob, "icon_state") or ""
    if k == "Ultimate":
        award = plain(var(path, "ascension_achievement"))
        if award:
            return plain(var(award, "icon")) or "", var(award, "icon_state") or ""
    return "icons/mob/actions/actions_ecult.dmi", "eye"


def atoms(v):
    out = []
    for key, amount in assoc(v):
        if isinstance(key, dict) and "list" in key:
            options = [plain(x) for x in key["list"]]
        else:
            options = [plain(key)]
        out.append("(&[" + ", ".join(rs(o) for o in options) + f"], {int(amount)})")
    return "&[" + ", ".join(out) + "]"


knowledge = [
    p
    for p in types
    if is_under(p, "/datum/heretic_knowledge") and not p.startswith("/datum/heretic_knowledge_")
    and not abstract(p)
]

lines = [
    "// Generated by `scripts/gen-heretic-data.py` from the DM dump and",
    "// `strings/antagonist_flavor/heretic_influences.json`. Do not edit: rerun the script.",
    "",
    "use super::knowledge::{Kind, KnowledgeDef, PassiveDef, PathDef};",
    "",
    "/// Every non-abstract `/datum/heretic_knowledge` in `subtypesof` order.",
    "pub static KNOWLEDGE: &[KnowledgeDef] = &[",
]
for p in knowledge:
    dmi, state = icon_of(p)
    action = plain(var(p, "action_to_add")) if kind(p) == "Spell" else None
    lines += [
        "    KnowledgeDef {",
        f"        path: {rs(p)},",
        f"        kind: Kind::{kind(p)},",
        f"        name: {rs(var(p, 'name'))},",
        f"        desc: {rs(var(p, 'desc'))},",
        f"        gain_text: {rs(var(p, 'gain_text'))},",
        f"        transmute_text: {rs(var(p, 'transmute_text'))},",
        f"        notice: {rs(var(p, 'notice'))},",
        f"        cost: {int(num(var(p, 'cost')))},",
        f"        priority: {int(num(var(p, 'priority')))},",
        f"        drafting_tier: {int(num(var(p, 'drafting_tier')))},",
        f"        shop_only: {'true' if var(p, 'is_shop_only') else 'false'},",
        f"        starting: {'true' if var(p, 'is_starting_knowledge') else 'false'},",
        f"        is_final: {'true' if var(p, 'is_final_knowledge') else 'false'},",
        f"        required: {atoms(var(p, 'required_atoms'))},",
        "        results: &[" + ", ".join(rs(plain(x)) for x in lst(var(p, "result_atoms"))) + "],",
        f"        limit: {int(num(var(p, 'limit'), 0))},",
        f"        max_charges: {min(int(num(var(p, 'max_charges'), 0)), 4294967295) if kind(p) == 'Spell' else 0},",
        f"        action: {rs(action or '')},",
        f"        action_name: {rs(var(action, 'name') if action else '')},",
        f"        icon: ({rs(dmi)}, {rs(state)}),",
        f"        announcement: {rs(var(p, 'announcement_text') if kind(p) == 'Ultimate' else '')},",
        "    },",
    ]
lines.append("];")
lines.append("")

columns = [
    p
    for p in types
    if is_under(p, "/datum/heretic_knowledge_tree_column") and not abstract(p)
]
lines.append("/// Every `/datum/heretic_knowledge_tree_column` (`GLOB.heretic_path_datums`).")
lines.append("pub static PATHS: &[PathDef] = &[")
for p in columns:
    icon = dict(assoc(var(p, "icon")))
    start = plain(var(p, "start"))
    passive = plain(var(start, "eldritch_passive"))
    strs = lambda name: "&[" + ", ".join(rs(x) for x in lst(var(p, name))) + "]"
    opt = lambda name: rs(plain(var(p, name)) or "")
    lines += [
        "    PathDef {",
        f"        route: {rs(var(p, 'route'))},",
        f"        ui_bgr: {rs(var(p, 'ui_bgr'))},",
        f"        complexity: {rs(var(p, 'complexity'))},",
        f"        complexity_color: {rs(var(p, 'complexity_color'))},",
        f"        icon: ({rs(plain(icon.get('icon')))}, {rs(icon.get('state'))}),",
        f"        description: {strs('description')},",
        f"        pros: {strs('pros')},",
        f"        cons: {strs('cons')},",
        f"        tips: {strs('tips')},",
        f"        start: {opt('start')},",
        f"        tier1: {opt('knowledge_tier1')},",
        f"        tier2: {opt('knowledge_tier2')},",
        f"        robes: {opt('robes')},",
        f"        tier3: {opt('knowledge_tier3')},",
        f"        blade: {opt('blade')},",
        f"        tier4: {opt('knowledge_tier4')},",
        f"        ascension: {opt('ascension')},",
        "        guaranteed: ["
        + ", ".join(opt(f"guaranteed_side_tier{i}") for i in (1, 2, 3))
        + "],",
        f"        shop_cost_discount: {int(num(var(p, 'shop_cost_discount')))},",
        "        passive: PassiveDef {",
        f"            name: {rs(var(passive, 'name'))},",
        f"            recharge: {rs(var(passive, 'recharge_description'))},",
        "            descriptions: &["
        + ", ".join(rs(x) for x in lst(var(passive, "passive_descriptions")))
        + "],",
        "        },",
        "    },",
    ]
lines.append("];")
lines.append("")

for key in ["prefix", "postfix", "drained", "drain_message", "examine"]:
    lines.append(f"/// `heretic_influences.json` `{key}`.")
    lines.append(
        f"pub static INFLUENCE_{key.upper()}: &[&str] = &["
        + ", ".join(rs(x) for x in strings.get(key, []))
        + "];"
    )
lines.append("")

with open(OUT, "w") as f:
    f.write("\n".join(lines))
print(f"wrote {OUT}: {len(knowledge)} knowledge, {len(columns)} paths")
